// Writes convex/lib/tv/eventFonts.ts: the latin subset of the two brand fonts
// as hex, for the generated event slide (lib/tv/eventSlide.ts). Convex
// bundles only code, so the font bytes travel as a module. Run after a
// @fontsource-variable bump: bun run tv:fonts (then bun run format).
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const TARGET = new URL("../convex/lib/tv/eventFonts.ts", import.meta.url);

/** Same faces as packages/design-system/src/styles/fonts.scss, latin subset only. */
const FONTS = {
	body: {
		file: "manrope.woff2",
		family: "Manrope",
		weights: "200 800",
		source: "@fontsource-variable/manrope/files/manrope-latin-wght-normal.woff2",
	},
	display: {
		file: "azeret-mono.woff2",
		family: "Azeret Mono",
		weights: "100 900",
		source: "@fontsource-variable/azeret-mono/files/azeret-mono-latin-wght-normal.woff2",
	},
} as const;

function entry(key: string, font: (typeof FONTS)[keyof typeof FONTS]): string {
	const hex = readFileSync(require.resolve(font.source)).toString("hex");
	return [
		`\t${key}: {`,
		`\t\tfile: "${font.file}",`,
		`\t\tfamily: "${font.family}",`,
		`\t\tweights: "${font.weights}",`,
		`\t\tsource: "${font.source}",`,
		`\t\thex: "${hex}",`,
		"\t},",
	].join("\n");
}

const text = [
	"// Generated by apps/web/scripts/gen-event-fonts.ts (bun run tv:fonts). Do not edit.",
	"// The latin subset of the J floor brand fonts, for the generated event slide, as hex",
	"// (hex digits cannot spell a lock vendor name by chance, which base64 can).",
	"// Manrope: Copyright 2019 The Manrope Project Authors (https://github.com/sharanda/manrope).",
	"// Azeret Mono: Copyright 2021 The Azeret Project Authors (https://github.com/displaay/azeret).",
	"// Both are licensed under the SIL Open Font License, Version 1.1: https://openfontlicense.org (https://scripts.sil.org/OFL).",
	"export const EVENT_FONTS = {",
	entry("body", FONTS.body),
	entry("display", FONTS.display),
	"} as const;",
	"",
].join("\n");

writeFileSync(TARGET, text);
console.log(`wrote ${TARGET.pathname}`);
